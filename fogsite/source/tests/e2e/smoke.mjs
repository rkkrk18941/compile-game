import { chromium } from 'playwright';
const OUT = '/tmp/claude-0/shots';
const browser = await chromium.launch({ args: ['--use-gl=swiftshader', '--enable-webgl', '--ignore-gpu-blocklist'] });
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
const page = await ctx.newPage();
const errors = [];
page.on('console', m => { if (m.type() === 'error' || m.type() === 'warning') errors.push(`[${m.type()}] ${m.text()}`); });
page.on('pageerror', e => errors.push(`[pageerror] ${e.message}\n${e.stack}`));
await page.goto('http://localhost:8790/', { waitUntil: 'networkidle' }).catch(() => {});
await page.waitForTimeout(1500);
await page.screenshot({ path: `${OUT}/01-title.png` });
await page.fill('input.input', 'テスト隊長');
await page.getByText('ひとりでCPUと遊ぶ').click();
await page.waitForTimeout(400);
await page.screenshot({ path: `${OUT}/02-cpu-menu.png` });
await page.getByText('はじめる').click();
await page.waitForTimeout(800);
await page.screenshot({ path: `${OUT}/03-setup.png`, fullPage: true });
console.log(errors.join('\n'));
await browser.close();
