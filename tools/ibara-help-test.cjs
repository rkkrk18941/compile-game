/* DOM integration checks for the read-only reference. Requires jsdom (test-only).
   NODE_PATH=/tmp/ibara-help-test/node_modules node tools/ibara-help-test.cjs */
'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { JSDOM, VirtualConsole } = require('jsdom');
const root = path.join(__dirname, '..');
const errors = [];
const vc = new VirtualConsole();
vc.on('jsdomError', e => errors.push(e.cause ? e.cause.stack : String(e))); vc.on('error', e => errors.push(String(e)));
const dom = new JSDOM('<div id="app"></div><div id="toast"></div><div id="floatLayer"></div>', { url: 'https://example.test/ibara/', runScripts: 'outside-only', pretendToBeVisual: true, virtualConsole: vc });
const w = dom.window, doc = w.document;
for (const file of ['data', 'cards', 'items', 'monsters', 'events', 'combat', 'engine', 'session', 'help', 'ui-parts', 'help-ui', 'ui']) w.eval(fs.readFileSync(path.join(root, 'ibara/bg', file + '.js'), 'utf8'));
const S = w.STS, H = S.Help, U = S.HelpUI, A = S.UI.state;
const tick = () => new Promise(resolve => setTimeout(resolve, 35));
const click = sel => { const el = doc.querySelector(sel); assert.ok(el, 'missing ' + sel); el.click(); };
const input = val => { const el = doc.getElementById('helpSearch'); el.value = val; el.dispatchEvent(new w.Event('input', { bubbles: true })); };
(async () => {
  await tick();
  assert.match(doc.getElementById('app').textContent, /用語・効果の解説/);
  for (const name of Object.values(S.DATA.TERMS)) assert.ok(H.findTerms(name).length, 'unexplained rule term: ' + name);
  assert.ok(!H.mark('プレイヤー', true).includes('data-help'), 'do not split longer katakana words');
  assert.ok(H.mark('プレイ', true).includes('term:play'), 'standalone word remains explained');
  assert.ok(H.mark('HPを2失う', true).includes('term:losehp'), 'numeric HP loss uses the block-bypassing explanation');
  const catalog = H.catalog();
  assert.equal(new Set(catalog.map(d => d.key)).size, catalog.length, 'unique reference keys');
  assert.equal(catalog.filter(d => d.kind === 'card').length, Object.keys(S.CARDS).length);
  for (const d of catalog) {
    assert.ok(d.text.trim(), d.key + ' text');
    U.open(d.key);
    assert.equal(doc.getElementById('helpTitle').textContent, d.name);
    assert.ok(!doc.querySelector('#referenceRoot [data-a]'), 'reference must not issue gameplay actions');
    const text = doc.getElementById('referenceRoot').textContent;
    assert.ok(!/undefined|NaN|表示エラー/.test(text), d.key + ' rendered without missing values');
    assert.ok(doc.querySelector('[data-help-close]'));
    click('[data-help-close]');
  }
  console.log('ok: ' + catalog.length + ' complete reference entries render, including all locked cards and enemy variants');
  click('[data-a="go"][data-v="solo"]'); await tick();
  click('.charbtn[data-v="B"]'); await tick();
  const setupBefore = JSON.stringify(A.setup);
  click('[data-help="hero:B"]');
  assert.match(doc.getElementById('referenceRoot').textContent, /戦闘開始時/);
  click('#referenceRoot [data-help="term:lightning"]');
  assert.match(doc.getElementById('helpTitle').textContent, /ライトニング/);
  click('[data-help-back]');
  assert.equal(doc.getElementById('helpTitle').textContent, 'ディフェクト');
  click('[data-help-close]');
  assert.equal(JSON.stringify(A.setup), setupBefore);
  click('[data-help="term:ascension"]');
  assert.match(doc.getElementById('referenceRoot').textContent, /13：第3幕ボス2連戦/);
  click('[data-help-close]');
  click('.page > [data-help=""]');
  input('すとらいく');
  assert.equal(U.state.group, '', 'typing switches context-only view to full search');
  assert.ok(doc.querySelectorAll('.help-result').length >= 4, 'hiragana name search');
  input(' ブロック   廃棄 ');
  assert.ok(doc.querySelectorAll('.help-result').length > 0, 'multi-word effect search');
  input('<img src=x onerror=alert(1)>');
  assert.equal(doc.querySelectorAll('.help-result').length, 0);
  assert.equal(doc.querySelectorAll('#referenceRoot img').length, 0, 'escaped user input');
  input('ライトニング'); click('.help-result[data-help="term:lightning"]');
  click('[data-help-back]'); assert.equal(doc.getElementById('helpSearch').value, 'ライトニング');
  click('[data-help-close]');
  assert.equal(doc.getElementById('app').inert, false);
  console.log('ok: setup links, nested help/back, all Ascension levels, context, search, escaping and return state');

  // Drive the actual UI against a fixed session: inspection must never play a card or accept a reward.
  const run = S.Game.newRun({ players: [{ ch: 'B' }], seed: 42, asc: 0 });
  const g = new S.Game(run, {}); g.setupDecks(); g.setupAct(1);
  const cb = S.Combat.create(g, { kind: 'normal' }); run.combat = cb.s; cb.s.phase = 'play'; run.phase = 'combat';
  const pc = cb.pcs()[0]; pc.en = 3; pc.t = { played: 0, attacks: 0, skills: 0, powers: 0, discarded: 0 };
  const card = { u: g.uid(), id: 'Zap', up: false }; pc.hand.push(card); cb.spawn('JawWorm', 0, { lvl: 'easy', beh: 'sda' });
  const calls = []; let pending = [];
  A.screen = 'game'; A.me = 0; A.ui = {};
  A.sess = { run: () => run, pending: () => pending, hand: () => S.Session.handInfo(run, 0), playOpen: () => true, command: (pi, cmd) => { calls.push(cmd); return Promise.resolve(); }, answer: (id, val) => calls.push({ id, val }) };
  S.UI.render(); await tick();
  assert.ok(!/表示エラー/.test(doc.getElementById('app').textContent));
  click('.hand [data-a="card"]'); await tick();
  assert.equal(A.ui.sel, card.u); const before = JSON.stringify(run);
  click('.preview [data-help="card:Zap"]');
  click('#referenceRoot [data-help="term:channel"]');
  click('[data-help-close]');
  assert.equal(JSON.stringify(run), before); assert.equal(A.ui.sel, card.u); assert.equal(calls.length, 0);
  click('.preview [data-a="playsel"]'); assert.equal(calls.length, 1, 'play still works after returning from help'); await tick();
  A.ui = {}; run.combat = null; run.phase = 'room';
  pending = [{ id: 93, pi: 0, q: { type: 'cardReward', title: 'カード報酬', cards: [{ id: 'Zap', idx: 0 }, { id: 'Dualcast', idx: 1 }], skip: true } }];
  S.UI.render(); await tick(); const beforeReward = JSON.stringify(run);
  click('.help-card-wrap [data-help="card:Zap"]'); click('[data-help-close]');
  assert.equal(calls.length, 1); assert.equal(JSON.stringify(run), beforeReward); assert.equal(pending[0].id, 93);
  click('.help-card-wrap .card'); assert.equal(calls.length, 2); assert.equal(calls[1].id, 93);
  assert.deepEqual(errors, []);
  console.log('ok: live card/target selection and reward prompt survive inspection without commands or state changes');
  dom.window.close();
})().catch(e => { console.error(e); dom.window.close(); process.exitCode = 1; });
